-- ============================================================================================
-- A task ID can now be logged by more than one person, but only once per person (by the email
-- the task is credited to). When someone logs a task ID that another team already logged, both
-- teams' leads get a notification. Run after 20261113_session_devices.sql.
-- ============================================================================================

begin;

-- Fails here if one person already has the same task ID twice in different letter case. Those
-- rows show on Data Quality → Duplicate Task IDs; remove one and run this again.
drop index if exists public.task_submissions_task_id_key;
create unique index if not exists task_submissions_task_id_cb_email_key
  on public.task_submissions (lower(task_id), lower(cb_email));

-- The lead of the team a submission belongs to: the credited person's lead, or the person
-- themselves when they're a lead. Null for an admin or someone with no lead.
create or replace function public.submission_team_lead(p_email text, p_user_id uuid)
returns uuid language sql stable security definer set search_path = public
as $$
  select case when p.role = 'lead' then p.id when p.role = 'contributor' then p.lead_id end
  from public.profiles p
  where p.id = coalesce((select e.id from public.profiles e where lower(e.email) = lower(p_email) limit 1), p_user_id)
$$;
revoke execute on function public.submission_team_lead(text, uuid) from public, anon, authenticated;

-- One row per lead to tell. Names are copied in because a lead can't read the other team's
-- submissions or people.
create table if not exists public.task_overlap_alerts (
  id bigint generated by default as identity primary key,
  lead_id uuid not null references public.profiles(id) on delete cascade,
  task_id text not null,
  submission_id bigint not null references public.task_submissions(id) on delete cascade,
  other_submission_id bigint not null references public.task_submissions(id) on delete cascade,
  logged_by text not null,
  logged_by_team text,
  other_by text not null,
  other_team text,
  created_at timestamptz not null default now(),
  read_at timestamptz,
  unique (lead_id, submission_id, other_submission_id)
);
create index if not exists task_overlap_alerts_unread_idx on public.task_overlap_alerts (lead_id, created_at desc) where read_at is null;

alter table public.task_overlap_alerts enable row level security;
revoke all on public.task_overlap_alerts from anon, authenticated;
grant select on public.task_overlap_alerts to authenticated;
grant update (read_at) on public.task_overlap_alerts to authenticated;

drop policy if exists "leads read own overlap alerts" on public.task_overlap_alerts;
create policy "leads read own overlap alerts" on public.task_overlap_alerts for select
  using (lead_id = auth.uid() and public.is_active_user());
drop policy if exists "leads mark own overlap alerts read" on public.task_overlap_alerts;
create policy "leads mark own overlap alerts read" on public.task_overlap_alerts for update
  using (lead_id = auth.uid() and public.is_active_user())
  with check (lead_id = auth.uid());

create or replace function public.task_overlap_notify()
returns trigger language plpgsql security definer set search_path = public
as $$
declare
  v_team uuid;
  v_name text;
  v_team_name text;
  o record;
  o_team uuid;
  o_name text;
  o_team_name text;
begin
  if new.task_id is null or trim(new.task_id) = '' then
    return new;
  end if;
  if tg_op = 'UPDATE' and lower(new.task_id) is not distinct from lower(old.task_id)
     and lower(new.cb_email) = lower(old.cb_email) then
    return new;
  end if;

  v_team := public.submission_team_lead(new.cb_email, new.user_id);
  select coalesce(nullif(trim(name), ''), new.cb_email) into v_name from public.profiles where lower(email) = lower(new.cb_email) limit 1;
  select name into v_team_name from public.profiles where id = v_team;

  for o in
    select s.id, s.cb_email, s.user_id from public.task_submissions s
    where lower(s.task_id) = lower(new.task_id) and s.id <> new.id and lower(s.cb_email) <> lower(new.cb_email)
  loop
    o_team := public.submission_team_lead(o.cb_email, o.user_id);
    if o_team is not distinct from v_team then
      continue;
    end if;
    select coalesce(nullif(trim(name), ''), o.cb_email) into o_name from public.profiles where lower(email) = lower(o.cb_email) limit 1;
    select name into o_team_name from public.profiles where id = o_team;

    insert into public.task_overlap_alerts (lead_id, task_id, submission_id, other_submission_id, logged_by, logged_by_team, other_by, other_team)
    select l, new.task_id, new.id, o.id, coalesce(v_name, new.cb_email), v_team_name, coalesce(o_name, o.cb_email), o_team_name
    from unnest(array[v_team, o_team]) as l
    where l is not null
    on conflict do nothing;
  end loop;

  return new;
end;
$$;
revoke execute on function public.task_overlap_notify() from public, anon, authenticated;

drop trigger if exists task_overlap_notify on public.task_submissions;
create trigger task_overlap_notify after insert or update of task_id, cb_email on public.task_submissions
  for each row execute function public.task_overlap_notify();

commit;

notify pgrst, 'reload schema';
