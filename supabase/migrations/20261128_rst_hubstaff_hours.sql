-- ============================================================================================
-- Hubstaff hours, for the RST team. Every RST contributor tracks their time in Hubstaff, which the
-- Tracker can't read, so each day they file the hours Hubstaff shows with a screenshot of it as
-- proof (kept in Google Drive through api/hubstaff-screenshot, never in Supabase).
--
-- A contributor files for today or yesterday (Singapore time); filing the same day again replaces
-- it. Their lead, the RST team manager and admins see the team's entries and can correct the
-- hours (the contributor's own figure is kept in filed_minutes). Run after 20261128_resource_team_scope.sql.
-- ============================================================================================

begin;

-- Each screenshot uploaded through api/hubstaff-screenshot (written with the service key). An entry
-- may only carry a ref its contributor uploaded, so nobody can attach (and so view) someone else's.
create table if not exists public.hubstaff_screenshot_uploads (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  drive_file_id text not null unique,
  created_at timestamptz not null default now()
);

create index if not exists hubstaff_screenshot_uploads_user_idx on public.hubstaff_screenshot_uploads(user_id, created_at desc);

alter table public.hubstaff_screenshot_uploads enable row level security;
-- No policies: only the service key (the upload endpoint) and the functions below touch it.

create table if not exists public.hubstaff_hours (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  date date not null,
  minutes integer not null check (minutes between 0 and 1440),
  filed_minutes integer not null check (filed_minutes between 0 and 1440),
  screenshot_ref text not null,
  corrected_by uuid references public.profiles(id) on delete set null,
  corrected_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, date)
);

create index if not exists hubstaff_hours_date_idx on public.hubstaff_hours(date desc);

alter table public.hubstaff_hours enable row level security;

drop policy if exists "own or team" on public.hubstaff_hours;
create policy "own or team" on public.hubstaff_hours for select to authenticated
  using (public.is_admin() or public.is_own_or_attached(user_id));
-- Writes only through file_hubstaff_hours() and correct_hubstaff_hours().

-- An active contributor on an RST team.
create or replace function public.can_file_hubstaff()
returns boolean language sql stable security definer set search_path = public
as $$
  select public.is_active_user()
    and exists (select 1 from public.profiles where id = auth.uid() and role = 'contributor')
    and public.team_program_of(auth.uid()) = 'rst'
$$;

-- p_screenshot_ref may be left out when replacing a day that already has a screenshot.
create or replace function public.file_hubstaff_hours(p_date date, p_minutes integer, p_screenshot_ref text default null)
returns bigint language plpgsql security definer set search_path = public
as $$
declare
  sg_today date := (now() at time zone 'Asia/Singapore')::date;
  v_ref text := nullif(trim(coalesce(p_screenshot_ref, '')), '');
  v_id bigint;
begin
  if not public.can_file_hubstaff() then
    raise exception 'Hubstaff hours are for RST contributors.';
  end if;
  if p_date is null or p_date not in (sg_today, sg_today - 1) then
    raise exception 'You can only file Hubstaff hours for today or yesterday.';
  end if;
  if p_minutes is null or p_minutes < 0 or p_minutes > 1440 then
    raise exception 'Enter the hours from your Hubstaff screenshot.';
  end if;

  if v_ref is not null then
    if not exists (select 1 from public.hubstaff_screenshot_uploads u where u.drive_file_id = v_ref and u.user_id = auth.uid()) then
      raise exception 'Upload your Hubstaff screenshot again.';
    end if;
  else
    select h.screenshot_ref into v_ref from public.hubstaff_hours h where h.user_id = auth.uid() and h.date = p_date;
    if v_ref is null then
      raise exception 'Add a screenshot of your Hubstaff hours.';
    end if;
  end if;

  insert into public.hubstaff_hours (user_id, date, minutes, filed_minutes, screenshot_ref)
  values (auth.uid(), p_date, p_minutes, p_minutes, v_ref)
  on conflict (user_id, date) do update
    set minutes = excluded.minutes,
        filed_minutes = excluded.filed_minutes,
        screenshot_ref = excluded.screenshot_ref,
        corrected_by = null,
        corrected_at = null,
        updated_at = now()
  returning id into v_id;

  return v_id;
end;
$$;

-- A lead (or the RST team manager, or an admin) sets the hours when they don't match the screenshot.
-- Setting them back to what the contributor filed clears the correction.
create or replace function public.correct_hubstaff_hours(p_id bigint, p_minutes integer)
returns void language plpgsql security definer set search_path = public
as $$
declare
  v_user uuid;
  v_filed integer;
begin
  select user_id, filed_minutes into v_user, v_filed from public.hubstaff_hours where id = p_id;
  if v_user is null then
    raise exception 'That entry was not found.';
  end if;
  if v_user = auth.uid() or not (public.is_admin() or (public.is_manager() and public.is_own_or_attached(v_user))) then
    raise exception 'Only the contributor''s lead can correct their hours.';
  end if;
  if p_minutes is null or p_minutes < 0 or p_minutes > 1440 then
    raise exception 'Enter hours between 0 and 24.';
  end if;

  update public.hubstaff_hours
    set minutes = p_minutes,
        corrected_by = case when p_minutes = v_filed then null else auth.uid() end,
        corrected_at = case when p_minutes = v_filed then null else now() end,
        updated_at = now()
  where id = p_id;
end;
$$;

-- For api/hubstaff-screenshot's GET: the screenshot is on an entry the caller can read, or is their
-- own upload not filed yet (so the form can preview it).
create or replace function public.can_view_hubstaff_screenshot(p_ref text)
returns boolean language sql stable security definer set search_path = public
as $$
  select public.is_active_user() and (
    exists (
      select 1 from public.hubstaff_hours h
      where h.screenshot_ref = p_ref and (public.is_admin() or public.is_own_or_attached(h.user_id))
    )
    or exists (select 1 from public.hubstaff_screenshot_uploads u where u.drive_file_id = p_ref and u.user_id = auth.uid())
  )
$$;

do $$
declare
  fn text;
begin
  foreach fn in array array[
    'can_file_hubstaff()',
    'file_hubstaff_hours(date, integer, text)',
    'correct_hubstaff_hours(bigint, integer)',
    'can_view_hubstaff_screenshot(text)'
  ] loop
    execute format('revoke execute on function public.%s from public, anon', fn);
    execute format('grant execute on function public.%s to authenticated', fn);
  end loop;
end;
$$;

commit;
