-- Daily attendance (replaces the "Centralize | Attendance" Google Form): one entry per person per
-- Singapore calendar day, with the hours they expect to put in and their tasking status. A
-- contributor files their own between 6:00 AM and 2:30 PM Singapore time (the same window the
-- dashboard's button uses, see src/lib/attendance.ts); a lead files or corrects one for their
-- attached contributors, and an admin for anyone, on any past day — the "support entry".

create table if not exists public.attendance (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  -- The Singapore calendar day this attendance is for.
  date date not null,
  -- 'absent', 'discontinued' and 'disabled' are support entries: only a lead or admin files them.
  hours text not null check (hours in ('1-2', '2-4', '4-6', '7+', 'absent', 'discontinued', 'disabled')),
  -- One of the statuses listed in src/lib/attendance.ts. Kept as free text (not a check
  -- constraint) so the list can change without a migration.
  tasking_status text not null check (char_length(trim(tasking_status)) between 1 and 120),
  -- Only set when tasking_status is 'Tasking'. "N/A" is accepted, as on the old form.
  task_id text check (char_length(task_id) <= 200),
  screenshot_url text check (char_length(screenshot_url) <= 1000),
  -- Who filed (or last changed) it: the contributor themselves, or the lead/admin who filed it for them.
  filed_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, date)
);

create index if not exists attendance_date_idx on public.attendance(date);

alter table public.attendance enable row level security;

-- A contributor sees their own, a lead their attached contributors' (and their own), an admin everyone's.
drop policy if exists "users read permitted attendance" on public.attendance;
create policy "users read permitted attendance" on public.attendance for select
  using (public.is_admin() or public.is_own_or_attached(user_id));

-- A lead removes an entry for their attached contributors, an admin any. A contributor can't: they
-- correct theirs by filing again while the window is open.
drop policy if exists "managers delete attendance" on public.attendance;
create policy "managers delete attendance" on public.attendance for delete
  using (public.is_admin() or (public.is_manager() and public.is_own_or_attached(user_id) and user_id <> auth.uid()));

-- No insert or update policies: every entry goes through here, so the window, the support-only
-- options and who-can-file-for-whom are checked in one place. Filing again for the same person and
-- day replaces that day's entry.
create or replace function public.file_attendance(
  p_user_id uuid,
  p_date date,
  p_hours text,
  p_tasking_status text,
  p_task_id text,
  p_screenshot_url text
)
returns bigint language plpgsql security definer set search_path = public
as $$
declare
  sg_now timestamp := now() at time zone 'Asia/Singapore';
  sg_minutes int := extract(hour from sg_now)::int * 60 + extract(minute from sg_now)::int;
  is_support boolean;
  v_status text := trim(coalesce(p_tasking_status, ''));
  v_task_id text := nullif(trim(coalesce(p_task_id, '')), '');
  v_screenshot text := nullif(trim(coalesce(p_screenshot_url, '')), '');
  v_id bigint;
begin
  if not public.is_active_user() then
    raise exception 'Sign in to file attendance.';
  end if;

  is_support := p_user_id <> auth.uid();

  if is_support then
    if not (public.is_admin() or (public.is_manager() and public.is_own_or_attached(p_user_id))) then
      raise exception 'You can only file attendance for your own team.';
    end if;
    if p_date > sg_now::date then
      raise exception 'Attendance can''t be filed for a future day.';
    end if;
  else
    if p_date <> sg_now::date then
      raise exception 'You can only file attendance for today.';
    end if;
    -- 6:00 AM – 2:30 PM Singapore time.
    if sg_minutes < 6 * 60 or sg_minutes >= 14 * 60 + 30 then
      raise exception 'Attendance is only taken from 6:00 AM to 2:30 PM.';
    end if;
    if p_hours in ('absent', 'discontinued', 'disabled') then
      raise exception 'Only your lead can file that.';
    end if;
  end if;

  if not exists (select 1 from public.profiles where id = p_user_id) then
    raise exception 'That person was not found.';
  end if;

  if v_status = '' then
    raise exception 'Pick a tasking status.';
  end if;

  if v_status = 'Tasking' then
    if v_task_id is null or v_screenshot is null then
      raise exception 'Add the Task ID and a screenshot link (or N/A).';
    end if;
  else
    v_task_id := null;
    v_screenshot := null;
  end if;

  insert into public.attendance (user_id, date, hours, tasking_status, task_id, screenshot_url, filed_by)
  values (p_user_id, p_date, p_hours, v_status, v_task_id, v_screenshot, auth.uid())
  on conflict (user_id, date) do update
    set hours = excluded.hours,
        tasking_status = excluded.tasking_status,
        task_id = excluded.task_id,
        screenshot_url = excluded.screenshot_url,
        filed_by = excluded.filed_by,
        updated_at = now()
  returning id into v_id;

  return v_id;
end;
$$;

grant execute on function public.file_attendance(uuid, date, text, text, text, text) to authenticated;

-- Signed-in people only (new functions are executable by everyone by default).
revoke execute on function public.file_attendance(uuid, date, text, text, text, text) from public, anon;
