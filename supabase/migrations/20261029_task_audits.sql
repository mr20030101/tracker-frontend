-- ============================================================================================
-- Task audits: a lead's spot check of a task one of their CBs logged, added from the Audits page,
-- with the score from the bootcamp rubric (5 perfect, 4 good, 3 fixable, 2 poor, 1 spam) and the
-- errors they found. Each audit belongs to one task submission, at most one audit per submission.
-- Run after 20261027_project_daily_quotas.sql.
-- ============================================================================================

-- An earlier draft of this migration made task_audits without task_submission_id. Replace that
-- table while it's still empty; if it has audits, stop rather than lose them.
do $$
begin
  if to_regclass('public.task_audits') is not null and not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'task_audits' and column_name = 'task_submission_id'
  ) then
    if exists (select 1 from public.task_audits) then
      raise exception 'public.task_audits is from an earlier draft and has audits in it. Move or delete them, then run this again.';
    end if;
    drop table public.task_audits;
  end if;
end;
$$;

create table if not exists public.task_audits (
  id bigint generated by default as identity primary key,
  task_submission_id bigint not null unique references public.task_submissions(id) on delete cascade,
  -- Copied from the submission by task_audits_fill() below, never sent by the client: the CB
  -- decides which lead can see and change the audit, task_id and project_id are for display.
  cb_user_id uuid not null references public.profiles(id) on delete cascade,
  task_id text not null,
  project_id bigint references public.projects(id) on delete set null,
  score smallint not null check (score between 1 and 5),
  errors text check (char_length(errors) <= 2000),
  audited_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists task_audits_cb_user_idx on public.task_audits(cb_user_id);
create index if not exists task_audits_created_at_idx on public.task_audits(created_at desc);

alter table public.task_audits enable row level security;

-- Leads audit their attached contributors' tasks (not their own), admins anyone's.
create or replace function public.can_audit_task(p_cb_user_id uuid)
returns boolean language sql stable security definer set search_path = public
as $$
  select public.is_admin()
    or (public.is_manager() and public.is_own_or_attached(p_cb_user_id) and p_cb_user_id <> auth.uid())
$$;

revoke execute on function public.can_audit_task(uuid) from public, anon;
grant execute on function public.can_audit_task(uuid) to authenticated;

-- The policies' checks run after this trigger, so they see the CB taken from the submission.
drop policy if exists "managers read task audits" on public.task_audits;
create policy "managers read task audits" on public.task_audits for select
  using (public.can_audit_task(cb_user_id));

drop policy if exists "managers add task audits" on public.task_audits;
create policy "managers add task audits" on public.task_audits for insert
  with check (public.can_audit_task(cb_user_id) and audited_by = auth.uid());

drop policy if exists "managers edit task audits" on public.task_audits;
create policy "managers edit task audits" on public.task_audits for update
  using (public.can_audit_task(cb_user_id))
  with check (public.can_audit_task(cb_user_id) and audited_by = auth.uid());

drop policy if exists "managers delete task audits" on public.task_audits;
create policy "managers delete task audits" on public.task_audits for delete
  using (public.can_audit_task(cb_user_id));

-- Fills the CB, task ID and project from the submission, and stamps updated_at with the server's
-- time. The CB is the profile with the submission's cb_email: a task a lead logs for a CB carries
-- the CB's email but the lead's user_id.
create or replace function public.task_audits_fill()
returns trigger language plpgsql security definer set search_path = public
as $$
declare
  v_cb uuid;
  v_task_id text;
  v_project_id bigint;
begin
  select p.id, s.task_id, s.project_id
  into v_cb, v_task_id, v_project_id
  from public.task_submissions s
  join public.profiles p on lower(p.email) = lower(s.cb_email)
  where s.id = new.task_submission_id;

  if v_cb is null then
    raise exception 'That task submission doesn''t exist, or its CB has no account.';
  end if;
  if v_task_id is null or trim(v_task_id) = '' then
    raise exception 'That task submission has no task ID yet.';
  end if;

  new.cb_user_id := v_cb;
  new.task_id := v_task_id;
  new.project_id := v_project_id;
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists task_audits_fill on public.task_audits;
create trigger task_audits_fill before insert or update on public.task_audits
  for each row execute function public.task_audits_fill();

-- Let the API see the new table and its link to task_submissions straight away.
notify pgrst, 'reload schema';
