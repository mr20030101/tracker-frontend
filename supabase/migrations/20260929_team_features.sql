-- Marks every announcement addressed to the caller as seen (the Announcements page calls it on open).
create or replace function public.mark_announcements_read()
returns void language sql security definer set search_path = public
as $$
  insert into public.announcement_reads (announcement_id, user_id)
  select a.id, auth.uid() from public.announcements a
  where public.announcement_addressed_to_me(a.audience, a.team_lead_id, a.project_id)
    and a.author_id <> auth.uid()
  on conflict do nothing
$$;

grant execute on function public.mark_announcements_read() to authenticated;

create or replace function public.unread_announcement_count()
returns bigint language sql stable security definer set search_path = public
as $$
  select count(*) from public.announcements a
  where public.announcement_addressed_to_me(a.audience, a.team_lead_id, a.project_id)
    and a.author_id <> auth.uid()
    and not exists (select 1 from public.announcement_reads r where r.announcement_id = a.id and r.user_id = auth.uid())
$$;

