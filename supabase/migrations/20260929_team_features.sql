-- Team features: an audit log of manager actions, announcements, the new-hire onboarding
-- checklist, streaks & badges, and group chats. Safe to re-run. The same statements are in
-- schema.sql.

-- directory() now also returns lead_id (to managers only), so the group-chat member picker can
-- fill in a whole team or project in one click. The return type changes, hence drop + create.
drop function if exists public.directory();
create function public.directory()
returns table (id uuid, name text, is_active boolean, last_seen_at timestamptz, avatar_url text, role text, is_bot boolean, email text, lead_id uuid)
language sql stable security definer set search_path = public
as $$
  select p.id, p.name, p.is_active,
    case when public.is_manager() or p.last_seen_at > now() - interval '3 minutes' then p.last_seen_at end,
    p.avatar_url, p.role, p.is_bot,
    case when public.is_manager() then p.email end,
    case when public.is_manager() then p.lead_id end
  from public.profiles p
  where p.is_active and public.is_active_user() and (
    public.is_manager()
    or p.is_bot
    or p.role = 'admin'
    or p.last_seen_at > now() - interval '3 minutes'
    or p.id = (select me.lead_id from public.profiles me where me.id = auth.uid())
    or exists (
      select 1 from public.messages m
      where (m.sender_id = auth.uid() and m.recipient_id = p.id)
         or (m.recipient_id = auth.uid() and m.sender_id = p.id)
    )
  )
$$;

grant execute on function public.directory() to authenticated;

-- ============================================================================================
-- Audit log: which manager did what, to whom. activity_logs only covers sign-ins; this covers
-- role/team/account changes, request reviews, levels, targets, projects and deleted tasks.
-- Rows come only from the triggers below (changes made through the app as a signed-in user) and
-- from the manage-user edge function (account and hiring actions, which run as the service role
-- and so carry no auth.uid() for a trigger to record). Admins read it; nobody can edit or delete
-- it through the API, which is the point of an audit trail.
-- ============================================================================================
create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid references public.profiles(id) on delete set null,
  action text not null check (char_length(action) between 1 and 60),
  target_user_id uuid references public.profiles(id) on delete set null,
  summary text not null check (char_length(summary) between 1 and 500),
  details jsonb,
  created_at timestamptz not null default now()
);

create index if not exists audit_logs_created_at_idx on public.audit_logs(created_at desc);
create index if not exists audit_logs_target_idx on public.audit_logs(target_user_id);

alter table public.audit_logs enable row level security;
drop policy if exists "admins read audit logs" on public.audit_logs;
create policy "admins read audit logs" on public.audit_logs for select using (public.is_admin());

-- Records one action by the signed-in caller. No caller (service role, SQL editor) means nothing
-- is recorded here: manage-user writes its own rows, and SQL-editor changes aren't app actions.
create or replace function public.write_audit(p_action text, p_target uuid, p_summary text, p_details jsonb default null)
returns void language plpgsql security definer set search_path = public
as $$
begin
  if auth.uid() is null then
    return;
  end if;
  insert into public.audit_logs (actor_id, action, target_user_id, summary, details)
  values (auth.uid(), p_action, p_target, left(p_summary, 500), p_details);
end;
$$;

-- Only the triggers below call it; a client calling it directly could write made-up history.
revoke execute on function public.write_audit(text, uuid, text, jsonb) from public, anon, authenticated;

create or replace function public.audit_profile_changes()
returns trigger language plpgsql security definer set search_path = public
as $$
declare
  old_lead text;
  new_lead text;
begin
  if auth.uid() is null then
    return null;
  end if;
  if new.role is distinct from old.role then
    perform public.write_audit('role_changed', new.id,
      format('Changed %s''s role from %s to %s', new.name, old.role, new.role),
      jsonb_build_object('from', old.role, 'to', new.role));
  end if;
  if new.lead_id is distinct from old.lead_id then
    select name into old_lead from public.profiles where id = old.lead_id;
    select name into new_lead from public.profiles where id = new.lead_id;
    perform public.write_audit('lead_changed', new.id,
      case when new.lead_id is null
        then format('Removed %s from %s''s team', new.name, coalesce(old_lead, 'their lead'))
        else format('Moved %s to %s''s team', new.name, coalesce(new_lead, 'another lead'))
      end,
      jsonb_build_object('from', old.lead_id, 'to', new.lead_id));
  end if;
  if new.is_active is distinct from old.is_active then
    perform public.write_audit(case when new.is_active then 'account_enabled' else 'account_disabled' end, new.id,
      format('%s %s''s account', case when new.is_active then 'Enabled' else 'Disabled' end, new.name));
  end if;
  -- Renaming yourself (Edit Profile) isn't a manager action.
  if new.name is distinct from old.name and new.id <> auth.uid() then
    perform public.write_audit('profile_renamed', new.id, format('Renamed %s to %s', old.name, new.name),
      jsonb_build_object('from', old.name, 'to', new.name));
  end if;
  return null;
end;
$$;

drop trigger if exists profiles_audit on public.profiles;
create trigger profiles_audit after update on public.profiles
  for each row execute function public.audit_profile_changes();

create or replace function public.audit_request_review()
returns trigger language plpgsql security definer set search_path = public
as $$
declare
  who text;
  task text;
begin
  if auth.uid() is null or new.status is not distinct from old.status or new.status = 'pending' then
    return null;
  end if;
  select name into who from public.profiles where id = new.requested_by;
  select task_id into task from public.task_submissions where id = new.task_submission_id;
  perform public.write_audit('request_' || new.status, new.requested_by,
    format('%s %s''s %s%s', initcap(new.status), coalesce(who, 'someone'),
      case new.type when 'bad_video' then 'bad video report' else new.type || ' request' end,
      coalesce(' for task ' || task, '')),
    jsonb_build_object('request_id', new.id, 'type', new.type));
  return null;
end;
$$;

drop trigger if exists task_requests_audit on public.task_requests;
create trigger task_requests_audit after update on public.task_requests
  for each row execute function public.audit_request_review();

create or replace function public.audit_level_change()
returns trigger language plpgsql security definer set search_path = public
as $$
declare
  r public.contributor_project_levels;
  who text;
  project text;
begin
  if auth.uid() is null then
    return null;
  end if;
  if tg_op = 'UPDATE' and new.level is not distinct from old.level then
    return null;
  end if;
  if tg_op = 'DELETE' then r := old; else r := new; end if;
  select name into who from public.profiles where id = r.user_id;
  select name into project from public.projects where id = r.project_id;
  -- Deleting a project or a person cascades here; that deletion is what gets recorded.
  if who is null or project is null then
    return null;
  end if;
  perform public.write_audit('level_changed', r.user_id,
    case when tg_op = 'DELETE'
      then format('Cleared %s''s level on %s', who, project)
      else format('Set %s''s level on %s to %s', who, project,
        case when r.level = 'contributor' then 'Contributor' else upper(r.level) end)
    end,
    jsonb_build_object('project_id', r.project_id, 'level', case when tg_op = 'DELETE' then null else r.level end));
  return null;
end;
$$;

drop trigger if exists contributor_project_levels_audit on public.contributor_project_levels;
create trigger contributor_project_levels_audit after insert or update or delete on public.contributor_project_levels
  for each row execute function public.audit_level_change();

