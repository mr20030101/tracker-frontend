-- ============================================================================================
-- Announcements: a post from a lead or admin to everyone, one lead's team, or one project, with
-- who has seen it. Posting rules: everyone = admins only; a team = that team's lead (or an admin);
-- a project = one of its leads (or an admin). The audience matches the rest of the app's scoping:
-- a team is the lead plus contributors whose lead_id is them; a project is its leads plus their
-- contributors (can_view_project()).
-- ============================================================================================
create table if not exists public.announcements (
  id bigint generated by default as identity primary key,
  author_id uuid not null references public.profiles(id) on delete cascade,
  audience text not null check (audience in ('everyone', 'team', 'project')),
  team_lead_id uuid references public.profiles(id) on delete cascade,
  project_id bigint references public.projects(id) on delete cascade,
  title text not null check (char_length(trim(title)) between 1 and 120),
  body text not null check (char_length(trim(body)) between 1 and 4000),
  pinned boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint announcements_audience_target check (
    (audience = 'everyone' and team_lead_id is null and project_id is null)
    or (audience = 'team' and team_lead_id is not null and project_id is null)
    or (audience = 'project' and project_id is not null and team_lead_id is null)
  )
);

create table if not exists public.announcement_reads (
  announcement_id bigint not null references public.announcements(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  read_at timestamptz not null default now(),
  primary key (announcement_id, user_id)
);

create index if not exists announcements_created_idx on public.announcements(pinned desc, created_at desc);
create index if not exists announcement_reads_user_idx on public.announcement_reads(user_id);

-- Whether an announcement is meant for the caller (not just visible to them: an admin can see
-- every team's posts, but a team post isn't addressed to them, so it never counts as unread and
-- their viewing it doesn't count as the team having seen it).
create or replace function public.announcement_addressed_to_me(p_audience text, p_team_lead_id uuid, p_project_id bigint)
returns boolean language sql stable security definer set search_path = public
as $$
  select public.is_active_user() and (
    p_audience = 'everyone'
    or (p_audience = 'team' and (
      p_team_lead_id = auth.uid()
      or exists (select 1 from public.profiles me where me.id = auth.uid() and me.lead_id = p_team_lead_id)
    ))
    or (p_audience = 'project' and (
      public.is_project_lead(p_project_id)
      or exists (
        select 1 from public.profiles me join public.project_leads pl on pl.lead_id = me.lead_id
        where me.id = auth.uid() and pl.project_id = p_project_id
      )
    ))
  )
$$;

create or replace function public.can_post_announcement(p_audience text, p_team_lead_id uuid, p_project_id bigint)
returns boolean language sql stable security definer set search_path = public
as $$
  select public.is_admin() or (
    public.is_manager() and (
      (p_audience = 'team' and p_team_lead_id = auth.uid())
      or (p_audience = 'project' and public.is_project_lead(p_project_id))
    )
  )
$$;

alter table public.announcements enable row level security;
alter table public.announcement_reads enable row level security;

