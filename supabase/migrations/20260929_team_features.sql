-- ============================================================================================
-- Group chats. Leads and admins create groups (e.g. a whole team or project); members chat in
-- them. Every change to a group or its membership goes through the functions below; the tables
-- only allow reading (members only) and posting a message into a group you're in.
-- ============================================================================================
create table if not exists public.chat_groups (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 1 and 80),
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.chat_group_members (
  group_id bigint not null references public.chat_groups(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role text not null default 'member' check (role in ('owner', 'member')),
  last_read_at timestamptz not null default now(),
  joined_at timestamptz not null default now(),
  primary key (group_id, user_id)
);

create table if not exists public.group_messages (
  id bigint generated by default as identity primary key,
  group_id bigint not null references public.chat_groups(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(trim(body)) > 0 and char_length(body) <= 2000),
  created_at timestamptz not null default now()
);

create index if not exists chat_group_members_user_idx on public.chat_group_members(user_id);
create index if not exists group_messages_group_idx on public.group_messages(group_id, id desc);

create or replace function public.is_group_member(p_group_id bigint)
returns boolean language sql stable security definer set search_path = public
as $$
  select public.is_active_user() and exists (
    select 1 from public.chat_group_members where group_id = p_group_id and user_id = auth.uid()
  )
$$;

-- The group's owner (its creator, or whoever they handed it to) or an admin who is in it.
create or replace function public.can_manage_group(p_group_id bigint)
returns boolean language sql stable security definer set search_path = public
as $$
  select public.is_active_user() and exists (
    select 1 from public.chat_group_members
    where group_id = p_group_id and user_id = auth.uid() and (role = 'owner' or public.is_admin())
  )
$$;

alter table public.chat_groups enable row level security;
alter table public.chat_group_members enable row level security;
alter table public.group_messages enable row level security;

drop policy if exists "members read groups" on public.chat_groups;
create policy "members read groups" on public.chat_groups for select using (public.is_group_member(id));
drop policy if exists "members read group members" on public.chat_group_members;
create policy "members read group members" on public.chat_group_members for select using (public.is_group_member(group_id));
drop policy if exists "members read group messages" on public.group_messages;
create policy "members read group messages" on public.group_messages for select using (public.is_group_member(group_id));
drop policy if exists "members post group messages" on public.group_messages;
create policy "members post group messages" on public.group_messages for insert
  with check (sender_id = auth.uid() and public.is_group_member(group_id));

-- Same spam guard as direct messages: 30 a minute across all groups.
create or replace function public.enforce_group_message_limits()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  if (select count(*) from public.group_messages where sender_id = new.sender_id and created_at > now() - interval '60 seconds') >= 30 then
    raise exception 'You are sending messages too fast. Please wait a moment.';
  end if;
  return new;
end;
$$;

drop trigger if exists group_messages_enforce_limits on public.group_messages;
create trigger group_messages_enforce_limits before insert on public.group_messages
  for each row execute function public.enforce_group_message_limits();

create or replace function public.create_chat_group(p_name text, p_member_ids uuid[])
returns bigint language plpgsql security definer set search_path = public
as $$
declare
  new_id bigint;
begin
  if not public.is_manager() then
    raise exception 'Only leads and admins can create group chats.';
  end if;
  if p_name is null or char_length(trim(p_name)) = 0 then
    raise exception 'Give the group a name.';
  end if;
  insert into public.chat_groups (name, created_by) values (trim(p_name), auth.uid()) returning id into new_id;
  insert into public.chat_group_members (group_id, user_id, role) values (new_id, auth.uid(), 'owner');
  insert into public.chat_group_members (group_id, user_id)
  select new_id, p.id from public.profiles p
  where p.id = any(coalesce(p_member_ids, '{}')) and p.id <> auth.uid() and p.is_active and not p.is_bot
  on conflict do nothing;
  return new_id;
end;
$$;

create or replace function public.add_chat_group_members(p_group_id bigint, p_member_ids uuid[])
returns void language plpgsql security definer set search_path = public
as $$
begin
  if not public.can_manage_group(p_group_id) then
    raise exception 'Only the group''s owner or an admin can add people.';
  end if;
  insert into public.chat_group_members (group_id, user_id, last_read_at)
  select p_group_id, p.id, now() from public.profiles p
  where p.id = any(coalesce(p_member_ids, '{}')) and p.is_active and not p.is_bot
  on conflict do nothing;
end;
$$;

-- Removes someone (owner/admin), or yourself (leaving). A group whose last member leaves is deleted.
create or replace function public.remove_chat_group_member(p_group_id bigint, p_user_id uuid)
returns void language plpgsql security definer set search_path = public
as $$
begin
  if p_user_id <> auth.uid() and not public.can_manage_group(p_group_id) then
    raise exception 'Only the group''s owner or an admin can remove people.';
  end if;
  if not public.is_group_member(p_group_id) then
    raise exception 'You are not in this group.';
  end if;
  delete from public.chat_group_members where group_id = p_group_id and user_id = p_user_id;
  if not exists (select 1 from public.chat_group_members where group_id = p_group_id) then
    delete from public.chat_groups where id = p_group_id;
  elsif not exists (select 1 from public.chat_group_members where group_id = p_group_id and role = 'owner') then
    -- The owner left: hand the group to whoever has been in it longest.
    update public.chat_group_members set role = 'owner'
    where (group_id, user_id) = (
      select group_id, user_id from public.chat_group_members where group_id = p_group_id order by joined_at limit 1
    );
  end if;
end;
$$;

create or replace function public.rename_chat_group(p_group_id bigint, p_name text)
returns void language plpgsql security definer set search_path = public
as $$
begin
  if not public.can_manage_group(p_group_id) then
    raise exception 'Only the group''s owner or an admin can rename it.';
  end if;
  if p_name is null or char_length(trim(p_name)) = 0 then
    raise exception 'Give the group a name.';
  end if;
  update public.chat_groups set name = trim(p_name) where id = p_group_id;
end;
$$;

create or replace function public.delete_chat_group(p_group_id bigint)
returns void language plpgsql security definer set search_path = public
as $$
begin
  if not public.can_manage_group(p_group_id) then
    raise exception 'Only the group''s owner or an admin can delete it.';
  end if;
  delete from public.chat_groups where id = p_group_id;
end;
$$;

create or replace function public.mark_chat_group_read(p_group_id bigint)
returns void language sql security definer set search_path = public
as $$
  update public.chat_group_members set last_read_at = now() where group_id = p_group_id and user_id = auth.uid()
$$;

-- The caller's groups for the inbox: members (names and photos, which profiles' read policy
-- wouldn't show a contributor), unread count and the latest message.
create or replace function public.chat_group_summaries()
returns table (id bigint, name text, my_role text, created_at timestamptz, unread_count bigint, last_message jsonb, members jsonb)
language sql stable security definer set search_path = public
as $$
  select g.id, g.name, me.role, g.created_at,
    (select count(*) from public.group_messages m
      where m.group_id = g.id and m.created_at > me.last_read_at and m.sender_id <> auth.uid()),
    (select to_jsonb(m) from public.group_messages m where m.group_id = g.id order by m.id desc limit 1),
    (select coalesce(jsonb_agg(jsonb_build_object('id', p.id, 'name', p.name, 'avatar_url', p.avatar_url, 'role', cm.role) order by p.name), '[]'::jsonb)
      from public.chat_group_members cm join public.profiles p on p.id = cm.user_id where cm.group_id = g.id)
  from public.chat_groups g
  join public.chat_group_members me on me.group_id = g.id and me.user_id = auth.uid()
  where public.is_active_user()
$$;

