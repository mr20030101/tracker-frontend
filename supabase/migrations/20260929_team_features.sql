  for each row execute function public.audit_announcement();

-- ============================================================================================
-- Onboarding checklist for new contributors. Most steps are read from real data (a photo, a
-- Remotasks ID, a shift, a first task, a first message to their lead); the two that can't be
-- (reading the guides, and hiding the checklist) are ticked by the contributor and kept here.
-- ============================================================================================
alter table public.profiles add column if not exists onboarding jsonb not null default '{}'::jsonb
  check (jsonb_typeof(onboarding) = 'object' and pg_column_size(onboarding) <= 1024);

create or replace function public.complete_onboarding_step(p_step text, p_done boolean default true)
returns void language plpgsql security definer set search_path = public
as $$
begin
  if p_step not in ('read_resources', 'dismissed') then
    raise exception 'Unknown onboarding step.';
  end if;
  update public.profiles
  set onboarding = case when p_done
      then onboarding || jsonb_build_object(p_step, now())
      else onboarding - p_step
    end
  where id = auth.uid() and public.is_active_user();
end;
$$;

grant execute on function public.complete_onboarding_step(text, boolean) to authenticated;

-- Checklist state for the given contributors: the caller themselves, their own team (a lead), or
-- anyone (an admin). Others are silently left out, so a list of ids is safe to pass as-is.
create or replace function public.onboarding_status(p_user_ids uuid[])
returns table (user_id uuid, steps jsonb, done integer, total integer, dismissed boolean)
language sql stable security definer set search_path = public
as $$
  with people as (
    select p.* from public.profiles p
    where p.id = any(p_user_ids) and p.role = 'contributor'
      and (public.is_admin() or public.is_own_or_attached(p.id))
  ),
  checks as (
    select pe.id,
      jsonb_build_object(
        'photo', pe.avatar_url is not null,
        'remotasks_id', pe.remotasks_id is not null,
        'shift', pe.shift is not null,
        'read_resources', pe.onboarding ? 'read_resources',
        'first_task', exists (
          select 1 from public.task_submissions s where s.user_id = pe.id or lower(s.cb_email) = lower(pe.email)
        ),
        'message_lead', pe.lead_id is not null and exists (
          select 1 from public.messages m where m.sender_id = pe.id and m.recipient_id = pe.lead_id
        )
      ) as steps,
      pe.lead_id is not null as has_lead,
      pe.onboarding ? 'dismissed' as dismissed
    from people pe
  )
  select c.id, c.steps,
    (select count(*) from jsonb_each(c.steps) e where e.value = 'true'::jsonb and (c.has_lead or e.key <> 'message_lead'))::integer,
    (case when c.has_lead then 6 else 5 end)::integer,
    c.dismissed
  from checks c
$$;

grant execute on function public.onboarding_status(uuid[]) to authenticated;

-- ============================================================================================
-- Streaks & badges. A week is the business week (Tuesday to Monday, Asia/Singapore). A week is
-- "hit" when the contributor submitted at least their target for it (50 unless set) and at least
-- one task. The current streak counts hit weeks back from the last finished week, plus this week
-- once it's hit; an unfinished week never breaks a streak. Public like contributor_public_stats():
-- only rollups, for contributors, to any active user.
-- ============================================================================================
create or replace function public.contributor_achievements(p_user_ids uuid[])
returns table (user_id uuid, current_streak integer, best_streak integer, weeks_hit integer, total_submitted bigint, best_week bigint)
language sql stable security definer set search_path = public
as $$
  with cw as (
    select d - ((extract(isodow from d)::int + 5) % 7) as ws
    from (select (now() at time zone 'Asia/Singapore')::date as d) t
  ),
  people as (
    select p.id, p.email from public.profiles p
    where p.id = any(p_user_ids) and p.role = 'contributor' and public.is_active_user()
  ),
  weekly as (
    select pe.id as user_id, (s.date - ((extract(isodow from s.date)::int + 5) % 7)) as week_start, count(*) as n
    from people pe
    join public.task_submissions s
      on s.status = 'submitted' and s.date is not null
     and (s.user_id = pe.id or lower(s.cb_email) = lower(pe.email))
    group by 1, 2
  ),
  weeks as (
    select f.user_id, gs::date as week_start
    from (select w.user_id, min(w.week_start) as first_week from weekly w group by w.user_id) f
    cross join lateral generate_series(f.first_week::timestamp, (select ws from cw)::timestamp, interval '7 days') gs
  ),
  flags as (
    select w.user_id, w.week_start, coalesce(wk.n, 0) as n,
      coalesce(wk.n, 0) > 0 and coalesce(wk.n, 0) >= coalesce(t.target, 50) as hit,
      w.week_start = (select ws from cw) as is_current
    from weeks w
    left join weekly wk on wk.user_id = w.user_id and wk.week_start = w.week_start
    left join public.weekly_targets t on t.user_id = w.user_id and t.week_start = w.week_start
  ),
  counted as (
    select * from flags where not is_current or hit
  ),
  islands as (
    select user_id, week_start, hit,
      row_number() over (partition by user_id order by week_start)
        - row_number() over (partition by user_id, hit order by week_start) as grp
    from counted
  ),
  runs as (
    select user_id, count(*)::integer as len, max(week_start) as last_week
    from islands where hit group by user_id, grp
  )
  select pe.id,
    coalesce((select r.len from runs r where r.user_id = pe.id and r.last_week >= (select ws from cw) - 7 order by r.last_week desc limit 1), 0),
    coalesce((select max(r.len) from runs r where r.user_id = pe.id), 0),
    (select count(*) from flags f where f.user_id = pe.id and f.hit)::integer,
    coalesce((select sum(w.n) from weekly w where w.user_id = pe.id), 0)::bigint,
    coalesce((select max(w.n) from weekly w where w.user_id = pe.id), 0)::bigint
  from people pe
$$;

