-- Who an announcement is for and who has seen it, for its author or an admin. Names come from
-- here rather than profiles, whose read policy wouldn't show a lead the other teams on a project.
create or replace function public.announcement_seen_by(p_announcement_id bigint)
returns table (user_id uuid, name text, avatar_url text, read_at timestamptz)
language sql stable security definer set search_path = public
as $$
  with a as (
    select * from public.announcements
    where id = p_announcement_id and (public.is_admin() or author_id = auth.uid()) and public.is_active_user()
  ),
  audience as (
    select a.id as announcement_id, p.id, p.name, p.avatar_url from public.profiles p, a
    where p.is_active and not p.is_bot and p.id <> a.author_id and (
      a.audience = 'everyone'
      or (a.audience = 'team' and (p.id = a.team_lead_id or p.lead_id = a.team_lead_id))
      or (a.audience = 'project' and (
        exists (select 1 from public.project_leads pl where pl.project_id = a.project_id and pl.lead_id = p.id)
        or exists (select 1 from public.project_leads pl where pl.project_id = a.project_id and pl.lead_id = p.lead_id)
      ))
    )
  )
  select au.id, au.name, au.avatar_url, r.read_at
  from audience au
  left join public.announcement_reads r on r.announcement_id = au.announcement_id and r.user_id = au.id
  order by r.read_at desc nulls last, au.name
$$;

grant execute on function public.announcement_seen_by(bigint) to authenticated;

create or replace function public.audit_announcement()
returns trigger language plpgsql security definer set search_path = public
as $$
declare
  target_name text;
begin
  if new.audience = 'team' then
    select name || '''s team' into target_name from public.profiles where id = new.team_lead_id;
  elsif new.audience = 'project' then
    select 'project ' || name into target_name from public.projects where id = new.project_id;
  end if;
  perform public.write_audit('announcement_posted', null,
    format('Posted "%s" to %s', new.title, coalesce(target_name, 'everyone')),
    jsonb_build_object('announcement_id', new.id));
  return null;
end;
$$;

drop trigger if exists announcements_audit on public.announcements;
