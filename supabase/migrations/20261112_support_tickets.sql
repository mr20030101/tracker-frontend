-- Support: anyone signed in reports a bug or asks for a feature, with up to three screenshots
-- (kept in Google Drive through api/support-screenshot, never in Supabase). The reporter sees
-- their own tickets; admins see every ticket, set its status and reply. Both sides can reply.

begin;

-- Each screenshot uploaded through api/support-screenshot (written with the service key). A ticket
-- may only carry refs its reporter uploaded, so nobody can attach (and so view) someone else's file.
create table if not exists public.support_screenshot_uploads (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  drive_file_id text not null unique,
  created_at timestamptz not null default now()
);

create index if not exists support_screenshot_uploads_user_idx on public.support_screenshot_uploads(user_id, created_at desc);

alter table public.support_screenshot_uploads enable row level security;
-- No policies: only the service key (the upload endpoint) and the functions below touch it.

create table if not exists public.support_tickets (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  kind text not null check (kind in ('bug', 'feature')),
  title text not null check (char_length(trim(title)) between 3 and 150),
  body text not null check (char_length(trim(body)) between 1 and 5000),
  -- Where it happened (the app page they came from) and what they were running, filled in by the app.
  page text check (char_length(page) <= 300),
  app_version text check (char_length(app_version) <= 40),
  user_agent text check (char_length(user_agent) <= 500),
  screenshot_refs text[] not null default '{}' check (cardinality(screenshot_refs) <= 3),
  status text not null default 'open' check (status in ('open', 'in_progress', 'done', 'wont_do')),
  status_changed_by uuid references public.profiles(id) on delete set null,
  status_changed_at timestamptz,
  -- Last time support (an admin who isn't the reporter) replied or changed the status, and last
  -- time the reporter opened the ticket: the reporter's Support badge counts the gap.
  support_activity_at timestamptz,
  reporter_seen_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists support_tickets_user_idx on public.support_tickets(user_id, created_at desc);
create index if not exists support_tickets_status_idx on public.support_tickets(status, created_at desc);

alter table public.support_tickets enable row level security;

drop policy if exists "users read own or all support tickets" on public.support_tickets;
create policy "users read own or all support tickets" on public.support_tickets for select
  using (public.is_admin() or (public.is_active_user() and user_id = auth.uid()));

-- Filed only as yourself, open, with your own uploads. Status and the support fields come from
-- set_support_ticket_status() and the reply trigger.
drop policy if exists "users file own support tickets" on public.support_tickets;
create policy "users file own support tickets" on public.support_tickets for insert
  with check (
    public.is_active_user()
    and user_id = auth.uid()
    and status = 'open' and status_changed_by is null and status_changed_at is null and support_activity_at is null
    -- At most 20 a day each, so a script can't flood the list.
    and (select count(*) from public.support_tickets mine where mine.user_id = auth.uid() and mine.created_at > now() - interval '1 day') < 20
    and not exists (
      select 1 from unnest(screenshot_refs) as ref
      where not exists (select 1 from public.support_screenshot_uploads u where u.drive_file_id = ref and u.user_id = auth.uid())
    )
  );

-- The clock is the server's, so a ticket can't be backdated past the daily cap above.
create or replace function public.support_ticket_stamp()
returns trigger language plpgsql set search_path = public
as $$
begin
  new.created_at := now();
  new.updated_at := now();
  new.reporter_seen_at := now();
  return new;
end;
$$;

drop trigger if exists support_tickets_stamp on public.support_tickets;
create trigger support_tickets_stamp
  before insert on public.support_tickets
  for each row execute function public.support_ticket_stamp();

-- The reporter withdraws their own ticket while it's still open; an admin deletes any.
drop policy if exists "users delete own open or any support ticket" on public.support_tickets;
create policy "users delete own open or any support ticket" on public.support_tickets for delete
  using (public.is_admin() or (public.is_active_user() and user_id = auth.uid() and status = 'open'));
-- No update policy: changes go through the functions below.

create table if not exists public.support_ticket_replies (
  id bigint generated by default as identity primary key,
  ticket_id bigint not null references public.support_tickets(id) on delete cascade,
  user_id uuid references public.profiles(id) on delete set null,
  body text not null check (char_length(trim(body)) between 1 and 5000),
  created_at timestamptz not null default now()
);

create index if not exists support_ticket_replies_ticket_idx on public.support_ticket_replies(ticket_id, created_at);

alter table public.support_ticket_replies enable row level security;

drop policy if exists "users read replies on visible tickets" on public.support_ticket_replies;
create policy "users read replies on visible tickets" on public.support_ticket_replies for select
  using (
    public.is_admin()
    or exists (select 1 from public.support_tickets t where t.id = ticket_id and t.user_id = auth.uid() and public.is_active_user())
  );

-- The reporter or an admin replies, as themselves.
drop policy if exists "users reply on own or any ticket" on public.support_ticket_replies;
create policy "users reply on own or any ticket" on public.support_ticket_replies for insert
  with check (
    public.is_active_user()
    and user_id = auth.uid()
    and (public.is_admin() or exists (select 1 from public.support_tickets t where t.id = ticket_id and t.user_id = auth.uid()))
  );

-- A reply moves the ticket's updated_at; one from support (not the reporter) also lights the
-- reporter's badge, and one from the reporter counts as them having seen it.
create or replace function public.support_reply_touch_ticket()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  update public.support_tickets t
  set updated_at = now(),
      support_activity_at = case when t.user_id <> new.user_id then now() else t.support_activity_at end,
      reporter_seen_at = case when t.user_id = new.user_id then now() else t.reporter_seen_at end
  where t.id = new.ticket_id;
  return new;
end;
$$;

revoke execute on function public.support_reply_touch_ticket() from public, anon, authenticated;

drop trigger if exists support_ticket_replies_touch on public.support_ticket_replies;
create trigger support_ticket_replies_touch
  after insert on public.support_ticket_replies
  for each row execute function public.support_reply_touch_ticket();

create or replace function public.set_support_ticket_status(p_id bigint, p_status text)
returns void language plpgsql security definer set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'Only an admin can change a ticket''s status.';
  end if;
  if p_status not in ('open', 'in_progress', 'done', 'wont_do') then
    raise exception 'Not a ticket status.';
  end if;

  update public.support_tickets t
  set status = p_status,
      status_changed_by = auth.uid(),
      status_changed_at = now(),
      updated_at = now(),
      support_activity_at = case when t.user_id <> auth.uid() then now() else t.support_activity_at end
  where t.id = p_id and t.status <> p_status;
end;
$$;

-- The reporter opened their ticket: clears it from their badge.
create or replace function public.mark_support_ticket_seen(p_id bigint)
returns void language sql security definer set search_path = public
as $$
  update public.support_tickets set reporter_seen_at = now()
  where id = p_id and user_id = auth.uid() and public.is_active_user()
$$;

-- The number on the Support link: for an admin, new (open) tickets from others; for anyone else,
-- their tickets support has replied to or moved since they last opened them.
create or replace function public.support_badge_count()
returns integer language sql stable security definer set search_path = public
as $$
  select case
    when not public.is_active_user() then 0
    when public.is_admin() then (select count(*)::int from public.support_tickets where status = 'open' and user_id <> auth.uid())
    else (select count(*)::int from public.support_tickets where user_id = auth.uid() and support_activity_at > reporter_seen_at)
  end
$$;

-- For api/support-screenshot's GET: the screenshot is on a ticket the caller can read.
create or replace function public.can_view_support_screenshot(p_ref text)
returns boolean language sql stable security definer set search_path = public
as $$
  select public.is_active_user() and (
    exists (
      select 1 from public.support_tickets t
      where p_ref = any(t.screenshot_refs) and (t.user_id = auth.uid() or public.is_admin())
    )
    -- Also your own upload before the ticket is filed, so the form can preview it.
    or exists (select 1 from public.support_screenshot_uploads u where u.drive_file_id = p_ref and u.user_id = auth.uid())
  )
$$;

grant execute on function public.set_support_ticket_status(bigint, text) to authenticated;
grant execute on function public.mark_support_ticket_seen(bigint) to authenticated;
grant execute on function public.can_view_support_screenshot(text) to authenticated;
grant execute on function public.support_badge_count() to authenticated;
revoke execute on function public.support_badge_count() from public, anon;
revoke execute on function public.set_support_ticket_status(bigint, text) from public, anon;
revoke execute on function public.mark_support_ticket_seen(bigint) from public, anon;
revoke execute on function public.can_view_support_screenshot(text) from public, anon;

commit;
