-- Photos in chat: direct messages and group messages can carry up to four images, kept in Google
-- Drive through api/chat-image (never in Supabase storage, so they cost no Supabase egress). A
-- message may only carry images its sender uploaded, and only the people in that chat can open one.

begin;

-- Each image uploaded through api/chat-image (written with the service key).
create table if not exists public.chat_image_uploads (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  drive_file_id text not null unique,
  created_at timestamptz not null default now()
);

create index if not exists chat_image_uploads_user_idx on public.chat_image_uploads(user_id, created_at desc);

alter table public.chat_image_uploads enable row level security;
-- No policies: only the service key (the upload endpoint) and the functions below touch it.

alter table public.messages add column if not exists image_refs text[] not null default '{}';
alter table public.group_messages add column if not exists image_refs text[] not null default '{}';

-- A photo on its own is a message too, so the "body can't be empty" checks now allow an empty body
-- when there are images. The old checks were unnamed, so they're found by what they test.
do $$
declare c record;
begin
  for c in
    select con.conrelid::regclass as tbl, con.conname
    from pg_constraint con
    where con.contype = 'c'
      and con.conrelid in ('public.messages'::regclass, 'public.group_messages'::regclass)
      and pg_get_constraintdef(con.oid) ilike '%body%'
  loop
    execute format('alter table %s drop constraint %I', c.tbl, c.conname);
  end loop;
end $$;

alter table public.messages add constraint messages_body_or_images check (
  (char_length(trim(body)) > 0 or cardinality(image_refs) > 0) and cardinality(image_refs) <= 4
);
alter table public.group_messages add constraint group_messages_body_or_images check (
  (char_length(trim(body)) > 0 or cardinality(image_refs) > 0) and char_length(body) <= 2000 and cardinality(image_refs) <= 4
);

-- Only your own uploads, so nobody can attach (and so view) someone else's file. No photos to the
-- FAQ bot: it only reads text.
drop policy if exists "only own chat images" on public.messages;
create policy "only own chat images" on public.messages as restrictive for insert to authenticated
  with check (
    cardinality(image_refs) = 0
    or (
      not coalesce((select is_bot from public.profiles where id = recipient_id), false)
      and not exists (
        select 1 from unnest(image_refs) as ref
        where not exists (select 1 from public.chat_image_uploads u where u.drive_file_id = ref and u.user_id = auth.uid())
      )
    )
  );

drop policy if exists "only own chat images" on public.group_messages;
create policy "only own chat images" on public.group_messages as restrictive for insert to authenticated
  with check (
    not exists (
      select 1 from unnest(image_refs) as ref
      where not exists (select 1 from public.chat_image_uploads u where u.drive_file_id = ref and u.user_id = auth.uid())
    )
  );

-- Same guard as schema.sql, now also covering image_refs.
create or replace function public.prevent_message_tampering()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  if new.body is distinct from old.body
    or new.image_refs is distinct from old.image_refs
    or new.sender_id is distinct from old.sender_id
    or new.recipient_id is distinct from old.recipient_id
    or new.created_at is distinct from old.created_at
  then
    raise exception 'Messages cannot be edited.';
  end if;

  if new.read_at is distinct from old.read_at and auth.uid() <> old.recipient_id then
    raise exception 'Only the recipient can mark a message read.';
  end if;

  if new.deleted_by_sender is distinct from old.deleted_by_sender and auth.uid() <> old.sender_id then
    raise exception 'Only the sender can delete their own copy of a message.';
  end if;

  if new.deleted_by_recipient is distinct from old.deleted_by_recipient and auth.uid() <> old.recipient_id then
    raise exception 'Only the recipient can delete their own copy of a message.';
  end if;

  return new;
end;
$$;

-- Whoever uploaded it, either side of a direct message that carries it (unless they deleted their
-- copy), or a current member of a group whose message carries it.
create or replace function public.can_view_chat_image(p_ref text)
returns boolean language sql stable security definer set search_path = public
as $$
  select public.is_active_user() and (
    exists (select 1 from public.chat_image_uploads u where u.drive_file_id = p_ref and u.user_id = auth.uid())
    or exists (
      select 1 from public.messages m
      where m.image_refs @> array[p_ref]
        and ((m.sender_id = auth.uid() and not m.deleted_by_sender) or (m.recipient_id = auth.uid() and not m.deleted_by_recipient))
    )
    or exists (
      select 1 from public.group_messages gm
      join public.chat_group_members cm on cm.group_id = gm.group_id and cm.user_id = auth.uid()
      where gm.image_refs @> array[p_ref]
    )
  )
$$;

create index if not exists messages_image_refs_idx on public.messages using gin (image_refs);
create index if not exists group_messages_image_refs_idx on public.group_messages using gin (image_refs);

revoke execute on function public.can_view_chat_image(text) from public, anon;
grant execute on function public.can_view_chat_image(text) to authenticated, service_role;

commit;
