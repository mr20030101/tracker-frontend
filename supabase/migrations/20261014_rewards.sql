-- ============================================================================================
-- Rewards: a lead (for their team) or an admin (for one team or everyone) offers a prize for a
-- rule over a date range, e.g. "next week, ₱1,000 for whoever submits the most tasks".
--
-- Rules, all counting submitted tasks dated inside the range (optionally one project only):
--   top_submitters        most tasks wins; prize_amounts[1] for 1st, [2] for 2nd, ... (places).
--                         threshold, when set, is the minimum to qualify at all. A tie goes to
--                         whoever reached that count first (their latest counted submission
--                         was logged earlier), so a prize is never split or paid twice by accident.
--   min_tasks             everyone with at least `threshold` tasks gets prize_amounts[1].
--   every_week_on_target  everyone on target in every business week (Tuesday to Monday) that falls
--                         wholly inside the range gets prize_amounts[1].
--   custom                the description says the rule; the lead picks the winners when awarding.
--                         prize_amounts[n] for the nth winner picked, the last amount for the rest.
--
-- Once the range is over, a manager awards it: the winners are worked out (or picked) and saved
-- in reward_winners, where each payout is then marked paid. Everything is written through the
-- functions below; the tables only allow reading, by the reward's audience and its managers.
-- ============================================================================================
create table if not exists public.rewards (
  id bigint generated by default as identity primary key,
  created_by uuid not null references public.profiles(id) on delete cascade,
  -- The team it's for (contributors whose lead_id is this). Null: everyone (admins only).
  team_lead_id uuid references public.profiles(id) on delete cascade,
  title text not null check (char_length(trim(title)) between 1 and 120),
  description text check (description is null or char_length(description) <= 1000),
  rule text not null check (rule in ('top_submitters', 'min_tasks', 'every_week_on_target', 'custom')),
  threshold integer check (threshold is null or threshold between 1 and 100000),
  places integer not null default 1 check (places between 1 and 10),
  project_id bigint references public.projects(id) on delete set null,
  prize_amounts numeric(12, 2)[] not null check (cardinality(prize_amounts) between 1 and 10 and 0 <= all(prize_amounts)),
  currency text not null default 'PHP' check (currency ~ '^[A-Z]{3}$'),
  prize_note text check (prize_note is null or char_length(prize_note) <= 200),
  starts_on date not null,
  ends_on date not null,
  status text not null default 'active' check (status in ('active', 'awarded', 'cancelled')),
  awarded_at timestamptz,
  created_at timestamptz not null default now(),
  constraint rewards_range check (ends_on >= starts_on and ends_on - starts_on <= 366),
  constraint rewards_min_tasks_threshold check (rule <> 'min_tasks' or threshold is not null)
);

create table if not exists public.reward_winners (
  reward_id bigint not null references public.rewards(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  place integer not null,
  amount numeric(12, 2) not null,
  submitted integer not null default 0,
  paid_at timestamptz,
  primary key (reward_id, user_id)
);

create index if not exists rewards_team_idx on public.rewards(team_lead_id, ends_on desc);

-- Today in Asia/Singapore, the app's calendar.
create or replace function public.sg_today()
returns date language sql stable
as $$ select (now() at time zone 'Asia/Singapore')::date $$;

-- A reward is for everyone (team_lead_id null) or one lead's team: that lead and their contributors.
create or replace function public.can_view_reward(p_team_lead_id uuid)
returns boolean language sql stable security definer set search_path = public
as $$
  select public.is_active_user() and (
    public.is_admin()
    or p_team_lead_id is null
    or p_team_lead_id = auth.uid()
    or exists (select 1 from public.profiles me where me.id = auth.uid() and me.lead_id = p_team_lead_id)
  )
$$;

-- Admins manage every reward; a lead manages their own team's.
create or replace function public.can_manage_reward(p_team_lead_id uuid)
returns boolean language sql stable security definer set search_path = public
as $$
  select public.is_admin() or (public.is_manager() and p_team_lead_id = auth.uid())
$$;

alter table public.rewards enable row level security;
alter table public.reward_winners enable row level security;

drop policy if exists "audience reads rewards" on public.rewards;
create policy "audience reads rewards" on public.rewards for select
  using (public.can_view_reward(team_lead_id));

drop policy if exists "audience reads reward winners" on public.reward_winners;
create policy "audience reads reward winners" on public.reward_winners for select
  using (exists (select 1 from public.rewards r where r.id = reward_id and public.can_view_reward(r.team_lead_id)));

-- Everyone in the reward's audience, with how they're doing on its rule right now. `place` is the
-- ranking for top_submitters (null otherwise); `qualifies` is whether they'd win if it ended now
-- (always false for custom, whose winners are picked).
create or replace function public.reward_standings(p_reward_id bigint)
returns table (
  user_id uuid, name text, avatar_url text, cb_email text,
  submitted integer, weeks_hit integer, weeks_total integer, reached_at timestamptz, place integer, qualifies boolean
)
language plpgsql stable security definer set search_path = public
as $$
declare
  r public.rewards;
  first_week date;
begin
  select * into r from public.rewards where id = p_reward_id;
  if r.id is null or not public.can_view_reward(r.team_lead_id) then
    return;
  end if;
  -- The first Tuesday on or after the start: weeks counted for every_week_on_target.
  first_week := r.starts_on + ((2 - extract(isodow from r.starts_on)::int + 7) % 7);

  return query
  with people as (
    select p.id, p.name, p.avatar_url, p.email from public.profiles p
    where p.role = 'contributor' and p.is_active and (r.team_lead_id is null or p.lead_id = r.team_lead_id)
  ),
  subs as (
    select pe.id as uid, s.date, s.created_at
    from people pe
    join public.task_submissions s
      on s.status = 'submitted' and s.date between r.starts_on and r.ends_on
     and (r.project_id is null or s.project_id = r.project_id)
     and (s.user_id = pe.id or lower(s.cb_email) = lower(pe.email))
  ),
  totals as (
    select x.uid, count(*)::integer as n, max(x.created_at) as reached from subs x group by x.uid
  ),
  weeks as (
    select gs::date as ws from generate_series(first_week::timestamp, (r.ends_on - 6)::timestamp, interval '7 days') gs
  ),
  weekly as (
    select pe.id as uid, w.ws,
      (select count(*) from subs x where x.uid = pe.id and x.date >= w.ws and x.date < w.ws + 7) as n,
      coalesce((select t.target from public.weekly_targets t where t.user_id = pe.id and t.week_start = w.ws), 50) as target
    from people pe cross join weeks w
  ),
  hits as (
    select wk.uid, count(*) filter (where wk.n > 0 and wk.n >= wk.target)::integer as hit from weekly wk group by wk.uid
  ),
  ranked as (
    select pe.id, pe.name, pe.avatar_url, pe.email,
      coalesce(t.n, 0) as n, t.reached,
      coalesce(h.hit, 0) as hit,
      (select count(*) from weeks)::integer as total,
      row_number() over (order by coalesce(t.n, 0) desc, t.reached asc nulls last, pe.name)::integer as rn
    from people pe
    left join totals t on t.uid = pe.id
    left join hits h on h.uid = pe.id
  )
  select k.id, k.name, k.avatar_url, k.email, k.n, k.hit, k.total, k.reached,
    case when r.rule = 'top_submitters' then k.rn end,
    case r.rule
      when 'top_submitters' then k.n >= greatest(coalesce(r.threshold, 1), 1) and k.rn <= r.places
      when 'min_tasks' then k.n >= r.threshold
      when 'every_week_on_target' then k.total > 0 and k.hit = k.total
      else false
    end
  from ranked k
  order by k.rn;
end;
$$;

-- Creates a reward, and (when p_announce) posts it to its audience as an announcement.
create or replace function public.create_reward(
  p_title text,
  p_description text,
  p_team_lead_id uuid,
  p_rule text,
  p_threshold integer,
  p_places integer,
  p_project_id bigint,
  p_prize_amounts numeric[],
  p_currency text,
  p_prize_note text,
  p_starts_on date,
  p_ends_on date,
  p_announce boolean default true
)
returns bigint language plpgsql security definer set search_path = public
as $$
declare
  new_id bigint;
  v_team uuid := p_team_lead_id;
  v_places integer := case when p_rule = 'top_submitters' then coalesce(p_places, 1) else 1 end;
begin
  -- A lead's reward is always for their own team; only an admin picks another team or everyone.
  if not public.is_admin() then
    if not public.is_manager() then
      raise exception 'Only leads and admins can create rewards.';
    end if;
    v_team := auth.uid();
  end if;
  if p_starts_on < public.sg_today() then
    raise exception 'A reward can''t start in the past.';
  end if;
  if p_rule = 'top_submitters' and cardinality(p_prize_amounts) < v_places then
    raise exception 'Give a prize for each of the % places.', v_places;
  end if;

  insert into public.rewards (
    created_by, team_lead_id, title, description, rule, threshold, places, project_id,
    prize_amounts, currency, prize_note, starts_on, ends_on
  ) values (
    auth.uid(), v_team, trim(p_title), nullif(trim(coalesce(p_description, '')), ''), p_rule,
    case when p_rule in ('top_submitters', 'min_tasks') then p_threshold end, v_places, p_project_id,
    case when p_rule = 'top_submitters' then p_prize_amounts[1:v_places] else p_prize_amounts end,
    upper(coalesce(nullif(trim(p_currency), ''), 'PHP')), nullif(trim(coalesce(p_prize_note, '')), ''),
    p_starts_on, p_ends_on
  ) returning id into new_id;

  if p_announce then
    insert into public.announcements (author_id, audience, team_lead_id, title, body)
    values (
      auth.uid(),
      case when v_team is null then 'everyone' else 'team' end,
      v_team,
      left('New reward: ' || trim(p_title), 120),
      left(concat_ws(E'\n\n', nullif(trim(coalesce(p_description, '')), ''),
        format('Runs %s to %s. See the Rewards page for the rules and how you''re doing.',
          to_char(p_starts_on, 'FMMon FMDD'), to_char(p_ends_on, 'FMMon FMDD, YYYY'))), 4000)
    );
  end if;

  perform public.write_audit('reward_created', null, format('Created the reward "%s"', trim(p_title)), jsonb_build_object('reward_id', new_id));
  return new_id;
end;
$$;

-- Saves the winners once the range is over. Automatic rules work them out from the standings; a
-- custom reward takes the picked people (p_user_ids, in place order). Optionally announces them.
create or replace function public.award_reward(p_reward_id bigint, p_user_ids uuid[] default null, p_announce boolean default true)
returns void language plpgsql security definer set search_path = public
as $$
declare
  r public.rewards;
  winner_names text;
begin
  select * into r from public.rewards where id = p_reward_id for update;
  if r.id is null or not public.can_manage_reward(r.team_lead_id) then
    raise exception 'Not allowed.';
  end if;
  if r.status <> 'active' then
    raise exception 'This reward has already been %.', r.status;
  end if;
  if r.ends_on >= public.sg_today() then
    raise exception 'This reward is still running. Award it once it ends.';
  end if;

  if r.rule = 'custom' then
    if coalesce(cardinality(p_user_ids), 0) = 0 then
      raise exception 'Pick at least one winner.';
    end if;
    insert into public.reward_winners (reward_id, user_id, place, amount, submitted)
    select r.id, s.user_id, picked.ord::integer,
      r.prize_amounts[least(picked.ord::integer, cardinality(r.prize_amounts))], s.submitted
    from unnest(p_user_ids) with ordinality as picked(uid, ord)
    join public.reward_standings(r.id) s on s.user_id = picked.uid;
  else
    insert into public.reward_winners (reward_id, user_id, place, amount, submitted)
    select r.id, s.user_id, coalesce(s.place, 1),
      case when r.rule = 'top_submitters' then r.prize_amounts[s.place] else r.prize_amounts[1] end, s.submitted
    from public.reward_standings(r.id) s
    where s.qualifies;
  end if;

  update public.rewards set status = 'awarded', awarded_at = now() where id = r.id;

  if p_announce then
    select string_agg(p.name, ', ' order by w.place, p.name) into winner_names
    from public.reward_winners w join public.profiles p on p.id = w.user_id
    where w.reward_id = r.id;

    insert into public.announcements (author_id, audience, team_lead_id, title, body)
    values (
      auth.uid(),
      case when r.team_lead_id is null then 'everyone' else 'team' end,
      r.team_lead_id,
      left('Reward winners: ' || r.title, 120),
      case when winner_names is null
        then 'Nobody met the rule this time. There''s always the next one!'
        else left(format('Congratulations to %s! 🎉', winner_names), 4000)
      end
    );
  end if;

  perform public.write_audit('reward_awarded', null, format('Awarded the reward "%s"', r.title), jsonb_build_object('reward_id', r.id));
end;
$$;

create or replace function public.cancel_reward(p_reward_id bigint)
returns void language plpgsql security definer set search_path = public
as $$
declare
  r public.rewards;
begin
  select * into r from public.rewards where id = p_reward_id for update;
  if r.id is null or not public.can_manage_reward(r.team_lead_id) then
    raise exception 'Not allowed.';
  end if;
  if r.status <> 'active' then
    raise exception 'Only a reward that hasn''t been awarded can be cancelled.';
  end if;
  update public.rewards set status = 'cancelled' where id = r.id;
  perform public.write_audit('reward_cancelled', null, format('Cancelled the reward "%s"', r.title), jsonb_build_object('reward_id', r.id));
end;
$$;

-- Marks one winner's prize as paid (or back to unpaid).
create or replace function public.set_reward_paid(p_reward_id bigint, p_user_id uuid, p_paid boolean)
returns void language plpgsql security definer set search_path = public
as $$
declare
  r public.rewards;
begin
  select * into r from public.rewards where id = p_reward_id;
  if r.id is null or not public.can_manage_reward(r.team_lead_id) then
    raise exception 'Not allowed.';
  end if;
  update public.reward_winners
  set paid_at = case when p_paid then now() end
  where reward_id = p_reward_id and user_id = p_user_id;
  if not found then
    raise exception 'They aren''t a winner of this reward.';
  end if;
  perform public.write_audit(case when p_paid then 'reward_paid' else 'reward_unpaid' end, p_user_id,
    format('Marked the "%s" prize %s', r.title, case when p_paid then 'paid' else 'unpaid' end), jsonb_build_object('reward_id', r.id));
end;
$$;

-- Signed-in people only (new functions are executable by everyone by default).
do $$
declare fn record;
begin
  for fn in
    select p.oid::regprocedure as sig
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public'
      and p.proname in ('can_view_reward', 'can_manage_reward', 'reward_standings', 'create_reward', 'award_reward', 'cancel_reward', 'set_reward_paid', 'sg_today')
  loop
    execute format('revoke execute on function %s from public, anon', fn.sig);
    execute format('grant execute on function %s to authenticated, service_role', fn.sig);
  end loop;
end $$;
