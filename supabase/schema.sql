-- Holds the two values bot_auto_reply() needs to call the bot-reply edge function: its URL, and a
-- dedicated shared secret (not the Supabase service role key — see the comment on
-- bot_auto_reply()'s webhook_secret) to authenticate as. `alter database ... set app.*` would be
-- the more usual way
-- to stash config like this for a plpgsql function to read via current_setting(), but Supabase's
-- hosted Postgres doesn't grant project accounts permission to set custom database parameters
-- (confirmed: "permission denied to set parameter" on that approach) — this table is the
-- workaround. RLS is enabled with deliberately zero policies, so every role reaches it only via a
-- security definer function (which bypasses RLS), never directly through the API/PostgREST.
create table if not exists public.app_secrets (
  key text primary key,
  value text not null
);

-- Auto-replies on behalf of the FAQ bot. Can't call Groq synchronously from plpgsql, so this just
-- notifies the bot-reply edge function (via pg_net, fire-and-forget) with the new message; that
-- function reads bot_faqs itself for grounding, calls Groq, and inserts the reply message using its
-- own service-role client — see supabase/functions/bot-reply/index.ts.
-- security definer (same as handle_new_user above) so it can read app_secrets despite that table
-- having no policies, and so the two keys in it are set once via a separate, uncommitted insert (see
-- the deployment notes) rather than living in this file.
-- bot_webhook_secret is a value we generated ourselves, not a real Supabase credential — it exists
-- only so bot-reply can tell this trigger apart from an arbitrary caller. Because it isn't a real
-- JWT, the bot-reply function must be deployed with `supabase functions deploy bot-reply
-- --no-verify-jwt`, or Supabase's platform gateway rejects the request before bot-reply's own code
-- (which checks this same secret) ever runs.
create or replace function public.bot_auto_reply()
returns trigger language plpgsql security definer set search_path = public
as $$
declare
  bot_id uuid := (select id from public.profiles where is_bot limit 1);
  reply_url text := (select value from public.app_secrets where key = 'bot_reply_url');
  -- A dedicated secret for this one handshake, not the Supabase service role key — see the comment
  -- on the same check in supabase/functions/bot-reply/index.ts for why.
  webhook_secret text := (select value from public.app_secrets where key = 'bot_webhook_secret');
begin
  if bot_id is null or new.recipient_id is distinct from bot_id or new.sender_id = bot_id then
    return new;
  end if;
  if reply_url is null or webhook_secret is null then
    return new;
  end if;
  perform net.http_post(
    url := reply_url,
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'Authorization', 'Bearer ' || webhook_secret
    ),
    body := jsonb_build_object(
      'message_id', new.id, 'sender_id', new.sender_id, 'recipient_id', new.recipient_id, 'body', new.body
    )
  );
  return new;
end;
$$;

drop trigger if exists on_message_to_bot on public.messages;
create trigger on_message_to_bot after insert on public.messages
for each row execute procedure public.bot_auto_reply();

