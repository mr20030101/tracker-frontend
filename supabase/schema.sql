create or replace function public.is_active_user()
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.profiles where id = auth.uid() and is_active) $$;

create or replace function public.is_manager()
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.profiles where id = auth.uid() and is_active and role in ('lead', 'admin')) $$;

-- Admins manage everyone; leads are scoped to their attached contributors
-- (see is_own_or_attached below) rather than the whole roster.
create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.profiles where id = auth.uid() and is_active and role = 'admin') $$;

-- True when profile_id is the caller's own id, or a contributor whose
-- lead_id points back at the caller. Used both for a profiles row (by its
-- id) and for a task_submissions/weekly_targets row (by its user_id).
create or replace function public.is_own_or_attached(profile_id uuid)
returns boolean language sql stable security definer set search_path = public
as $$
  select profile_id = auth.uid()
    or exists (select 1 from public.profiles where id = profile_id and lead_id = auth.uid())
$$;

-- Messaging is open to any active user regardless of lead attachment, so it
-- needs its own minimal, RLS-independent lookup rather than the profiles
-- table's (deliberately) scoped read policy.
-- Dropped first since CREATE OR REPLACE can't change a function's return type
-- (this one gained avatar_url after its first release).
drop function if exists public.directory();
create function public.directory()
returns table (id uuid, name text, is_active boolean, last_seen_at timestamptz, avatar_url text)
language sql stable security definer set search_path = public
as $$ select id, name, is_active, last_seen_at, avatar_url from public.profiles where is_active $$;

grant execute on function public.directory() to authenticated;

create or replace function public.is_active_profile(target_id uuid)
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.profiles where id = target_id and is_active) $$;

-- Lets any signed-in user rename themselves and set their own avatar without
-- granting a general self-update policy on profiles (which would also open
-- role/lead_id/is_active to direct tampering). Only name and avatar_url are
-- ever touched, and only for the caller's own row.
create or replace function public.update_own_profile(new_name text, new_avatar_url text)
returns public.profiles
language plpgsql security definer set search_path = public
as $$
declare
  updated public.profiles;
begin
  if new_name is null or trim(new_name) = '' then
    raise exception 'Name is required.';
  end if;

  update public.profiles
  set name = trim(new_name),
      avatar_url = new_avatar_url,
      updated_at = now()
  where id = auth.uid()
  returning * into updated;

  return updated;
end;
$$;

grant execute on function public.update_own_profile(text, text) to authenticated;

-- RLS is row-level only, so a lead permitted to update their attached
-- contributor's row could otherwise still smuggle a role change through.
-- This column-level guard blocks that regardless of which policy allowed
-- the row through. is_admin() checks auth.uid(), so this only applies to
-- requests made with a real user session — service-role calls (e.g. the
-- manage-user function) are unaffected since they don't change role via
-- UPDATE against an existing different value.
create or replace function public.prevent_non_admin_role_change()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  if new.role is distinct from old.role and not public.is_admin() then
    raise exception 'Only admins can change a user''s role.';
  end if;
  return new;
end;
$$;

drop trigger if exists profiles_prevent_non_admin_role_change on public.profiles;
create trigger profiles_prevent_non_admin_role_change
  before update on public.profiles
  for each row execute procedure public.prevent_non_admin_role_change();

-- A project may have multiple leads (see public.project_leads); this checks
-- whether the caller is one of them.
create or replace function public.is_project_lead(target_project_id bigint)
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.project_leads where project_id = target_project_id and lead_id = auth.uid()) $$;

-- Messages allow two kinds of update: the recipient marking read_at, and
-- either side hiding the message from their own view ("delete for me").
-- Column-level RLS doesn't exist, so this guard blocks anything else —
-- editing body/sender/recipient, or one side flipping the other's flag.
create or replace function public.prevent_message_tampering()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  if new.body is distinct from old.body
    or new.sender_id is distinct from old.sender_id
    or new.recipient_id is distinct from old.recipient_id
    or new.created_at is distinct from old.created_at
  then
    raise exception 'Messages cannot be edited.';
  end if;

  if new.read_at is distinct from old.read_at and auth.uid() <> old.recipient_id then
    raise exception 'Only the recipient can mark a message read.';
  end if;

  if new.deleted_by_sender is distinct from old.deleted_by_sender and auth.uid() <> old.sender_id then
    raise exception 'Only the sender can delete their own copy of a message.';
  end if;

  if new.deleted_by_recipient is distinct from old.deleted_by_recipient and auth.uid() <> old.recipient_id then
    raise exception 'Only the recipient can delete their own copy of a message.';
  end if;

  return new;
end;
$$;

drop trigger if exists messages_prevent_tampering on public.messages;
create trigger messages_prevent_tampering
  before update on public.messages
  for each row execute procedure public.prevent_message_tampering();

-- Lets a signed-in user stamp their own presence without granting general
-- update rights on profiles (only managers can update profiles otherwise).
create or replace function public.touch_presence()
returns void language sql security definer set search_path = public
as $$ update public.profiles set last_seen_at = now() where id = auth.uid() $$;

grant execute on function public.touch_presence() to authenticated;

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  insert into public.profiles (id, name, email, role)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'name', split_part(new.email, '@', 1)), new.email, coalesce(new.raw_user_meta_data ->> 'role', 'contributor'))
  on conflict (id) do update set email = excluded.email;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();

