create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  email text unique not null,
  role text not null default 'contributor' check (role in ('contributor', 'lead', 'admin')),
  shift text,
  meet_link text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  name text unique not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.task_submissions (
  id bigint generated by default as identity primary key,
  task_id text,
  cb_email text not null,
  user_id uuid references public.profiles(id) on delete set null,
  project_id bigint references public.projects(id) on delete set null,
  stage text not null default 'attempt' check (stage in ('attempt', 'l0', 'l1')),
  status text not null default 'in_progress' check (status in ('submitted', 'in_progress', 'empty')),
  notes text,
  date date,
  submitted_at date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.weekly_targets (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  week_start date not null,
  target integer not null default 50,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, week_start)
);

create table if not exists public.resources (
  id bigint generated by default as identity primary key,
  category text not null,
  title text not null,
  url text not null,
  project_id bigint references public.projects(id) on delete set null,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.house_rules (
  id bigint generated by default as identity primary key,
  project_id bigint references public.projects(id) on delete set null,
  type text not null default 'rule' check (type in ('info', 'rule')),
  title text,
  body text not null,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists task_submissions_user_id_idx on public.task_submissions(user_id);
create index if not exists task_submissions_cb_email_idx on public.task_submissions(cb_email);
create index if not exists task_submissions_date_idx on public.task_submissions(date);
create index if not exists resources_project_category_idx on public.resources(project_id, category, sort_order);
create index if not exists house_rules_project_idx on public.house_rules(project_id, sort_order);

create or replace function public.is_active_user()
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.profiles where id = auth.uid() and is_active) $$;

create or replace function public.is_manager()
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.profiles where id = auth.uid() and is_active and role in ('lead', 'admin')) $$;

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  insert into public.profiles (id, name, email, role)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'name', split_part(new.email, '@', 1)), new.email, coalesce(new.raw_user_meta_data ->> 'role', 'contributor'))
  on conflict (id) do update set email = excluded.email;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();

