- Misplacing the item.
- An unnecessary handover.
- Using the gripper farther from the object, or making unnatural movements.
- In-hand moving or re-orientation during a pour.
- Grabbing the object at arbitrary locations.
- A gravity-induced misfold.
- An object stuck in the gripper that needs the other gripper to free it.

