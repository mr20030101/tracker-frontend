-- Read-only from the client: an admin sees every application, a lead only
-- their own. There are deliberately no insert/update/delete policies —
-- applicants insert through submit_hiring_application() below, and
-- accept/deny goes through the manage-user edge function (service role).
drop policy if exists "leads read own applications" on public.hiring_applications;
create policy "leads read own applications" on public.hiring_applications for select
  using (public.is_admin() or (public.is_manager() and lead_id = auth.uid()));

-- Applicants aren't signed in, so the public form talks to the database
-- through these two narrow functions instead of the table.
-- Returns the lead's name and whether they're taking applications; no row means
