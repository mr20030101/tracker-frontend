-- Hiring: each lead has a public application link (/apply/<lead id>). An
-- applicant fills in the form; the lead reviews the entry and accepts or
-- denies it. Accepting creates the applicant's login on that lead's team.
-- Each lead can switch their application link on or off. It defaults to on, so
-- a lead's link works as soon as it's shared; turning it off closes the form
-- without touching applications already received. A lead flips their own
-- value through the existing "profiles managers update" policy.
alter table public.profiles add column if not exists accepting_applications boolean not null default true;

create table if not exists public.hiring_applications (
  id bigint generated by default as identity primary key,
  lead_id uuid not null references public.profiles(id) on delete cascade,
  remotasks_email text not null check (char_length(remotasks_email) between 3 and 254),
  remotasks_id text not null check (char_length(remotasks_id) between 1 and 200),
  full_name text not null check (char_length(full_name) between 1 and 200),
  active_email text not null check (char_length(active_email) between 3 and 254),
  facebook_url text not null check (char_length(facebook_url) between 1 and 500),
  has_robotics_background boolean not null,
  status text not null default 'pending' check (status in ('pending', 'accepted', 'denied')),
  reviewed_by uuid references public.profiles(id) on delete set null,
  reviewed_at timestamptz,
  -- The login created for this applicant. Accepting doesn't create it: an accepted applicant
  -- gets an account in a separate step (manage-user, create-account), so this is null until then.
  user_id uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

