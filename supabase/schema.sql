-- Admins see every profile; a lead sees only their own row plus contributors
-- attached to them (lead_id = their id); a contributor sees only their own row.
drop policy if exists "profiles read own or manager" on public.profiles;
create policy "profiles read own or manager" on public.profiles for select
  using (public.is_admin() or public.is_own_or_attached(id));
create policy "users create own profile" on public.profiles for insert with check (id = auth.uid() and role = 'contributor');
drop policy if exists "profiles managers update" on public.profiles;
create policy "profiles managers update" on public.profiles for update
  using (public.is_admin() or (public.is_manager() and public.is_own_or_attached(id)))
  with check (public.is_admin() or (public.is_manager() and public.is_own_or_attached(id)));

create policy "managers read activity logs" on public.activity_logs for select using (public.is_manager());
create policy "users log own auth events" on public.activity_logs for insert to authenticated
  with check (user_id = auth.uid() and event in ('login', 'logout'));
-- Failed sign-in attempts happen before a session exists, so they come in
-- unauthenticated (anon) and are restricted to that one event type with no user_id.
create policy "anon logs failed logins" on public.activity_logs for insert to anon
  with check (user_id is null and event = 'login_failed');

create policy "active users read projects" on public.projects for select using (public.is_active_user());
-- Admin creates and owns the master project list; a lead may only rename or
-- delete a project they're assigned to via project_leads — assignment
-- itself is admin-only (see "admins manage project leads" below).
drop policy if exists "managers manage projects" on public.projects;
drop policy if exists "admins or assigned lead update projects" on public.projects;
drop policy if exists "admins or assigned lead delete projects" on public.projects;
create policy "admins create projects" on public.projects for insert
  with check (public.is_admin());
create policy "admins or assigned lead update projects" on public.projects for update
  using (public.is_admin() or public.is_project_lead(id))
  with check (public.is_admin() or public.is_project_lead(id));
create policy "admins or assigned lead delete projects" on public.projects for delete
  using (public.is_admin() or public.is_project_lead(id));

-- Anyone can see who leads a project; only admins may assign/unassign leads.
create policy "active users read project leads" on public.project_leads for select
  using (public.is_active_user());
create policy "admins manage project leads" on public.project_leads for all
  using (public.is_admin()) with check (public.is_admin());

-- A contributor (or their lead) can read their own per-project levels; an
-- admin reads all. Writing is scoped further: only the lead who actually
-- runs that project (or an admin) may set a level for their own attached
-- contributor on it.
drop policy if exists "users read permitted project levels" on public.contributor_project_levels;
create policy "users read permitted project levels" on public.contributor_project_levels for select
  using (public.is_admin() or public.is_own_or_attached(user_id));
drop policy if exists "leads insert attached contributor project levels" on public.contributor_project_levels;
create policy "leads insert attached contributor project levels" on public.contributor_project_levels for insert
  with check (public.is_admin() or (public.is_own_or_attached(user_id) and public.is_project_lead(project_id)));
drop policy if exists "leads update attached contributor project levels" on public.contributor_project_levels;
create policy "leads update attached contributor project levels" on public.contributor_project_levels for update
  using (public.is_admin() or (public.is_own_or_attached(user_id) and public.is_project_lead(project_id)))
  with check (public.is_admin() or (public.is_own_or_attached(user_id) and public.is_project_lead(project_id)));
drop policy if exists "leads delete attached contributor project levels" on public.contributor_project_levels;
create policy "leads delete attached contributor project levels" on public.contributor_project_levels for delete
  using (public.is_admin() or (public.is_own_or_attached(user_id) and public.is_project_lead(project_id)));

