-- The signature gained the computer answers; CREATE OR REPLACE would leave the
-- old 7-argument version callable, letting an applicant skip step 2.
drop function if exists public.submit_hiring_application(uuid, text, text, text, text, text, boolean);
create or replace function public.submit_hiring_application(
  p_lead_id uuid,
  p_remotasks_email text,
  p_remotasks_id text,
  p_full_name text,
  p_active_email text,
  p_facebook_url text,
  p_has_robotics_background boolean,
  p_has_personal_computer boolean,
  p_has_stable_internet boolean,
  p_cpu text,
  p_gpu text,
  p_gpu_memory_gb numeric
)
returns void language plpgsql security definer set search_path = public
as $$
declare
  v_accepting boolean;
  v_remotasks_email text := lower(trim(coalesce(p_remotasks_email, '')));
  v_active_email text := lower(trim(coalesce(p_active_email, '')));
  v_remotasks_id text := trim(coalesce(p_remotasks_id, ''));
  v_full_name text := trim(coalesce(p_full_name, ''));
  v_facebook_url text := trim(coalesce(p_facebook_url, ''));
  v_cpu text := trim(coalesce(p_cpu, ''));
  v_gpu text := trim(coalesce(p_gpu, ''));
begin
  select accepting_applications into v_accepting
  from public.profiles where id = p_lead_id and role = 'lead' and is_active;

  if v_accepting is null then
    raise exception 'This application link is not valid.';
  end if;

  if not v_accepting then
    raise exception 'This lead is not accepting applications right now.';
  end if;

  if v_remotasks_email = '' or v_remotasks_id = '' or v_full_name = '' or v_active_email = '' or v_facebook_url = ''
    or p_has_robotics_background is null or p_has_personal_computer is null or p_has_stable_internet is null then
    raise exception 'Please answer every question.';
  end if;

  if v_remotasks_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' or v_active_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then
    raise exception 'Please enter a valid email address.';
  end if;

  if v_facebook_url !~* '^https?://\S+$' then
    raise exception 'Please enter your Facebook profile link.';
  end if;

  if p_gpu_memory_gb is not null and (p_gpu_memory_gb < 0 or p_gpu_memory_gb > 256) then
    raise exception 'Please enter your GPU memory in GB (0 if you have no dedicated GPU).';
  end if;

  if char_length(v_remotasks_email) > 254 or char_length(v_active_email) > 254 or char_length(v_remotasks_id) > 200
    or char_length(v_full_name) > 200 or char_length(v_facebook_url) > 500 or char_length(v_cpu) > 200 or char_length(v_gpu) > 200 then
    raise exception 'One of your answers is too long.';
  end if;

  if exists (
    select 1 from public.hiring_applications
    where lead_id = p_lead_id and lower(remotasks_email) = v_remotasks_email and status in ('pending', 'accepted')
  ) then
    raise exception 'An application with this Remotasks email has already been submitted.';
  end if;

  insert into public.hiring_applications
    (lead_id, remotasks_email, remotasks_id, full_name, active_email, facebook_url, has_robotics_background,
     has_personal_computer, has_stable_internet, cpu, gpu, gpu_memory_gb)
  values
    (p_lead_id, v_remotasks_email, v_remotasks_id, v_full_name, v_active_email, v_facebook_url, p_has_robotics_background,
     p_has_personal_computer, p_has_stable_internet, nullif(v_cpu, ''), nullif(v_gpu, ''), p_gpu_memory_gb);
exception
  -- Two submissions racing past the check above hit the unique index instead.
  when unique_violation then
    raise exception 'An application with this Remotasks email has already been submitted.';
end;
$$;

grant execute on function public.submit_hiring_application(uuid, text, text, text, text, text, boolean, boolean, boolean, text, text, numeric) to anon, authenticated;

-- Keep these functions away from signed-out visitors. Postgres (and Supabase's default privileges)
-- makes every new function executable by PUBLIC and anon, and the grants above only ADD authenticated
-- — so without this, anyone holding the public anon key could call them. directory() alone listed
-- every admin and everyone online to a stranger. Left public on purpose: hiring_lead_info() and
-- submit_hiring_application() (the Apply page has no login) and the is_*() helpers (row-level
-- security policies call them, and they only ever return false without a login). Sits at the end so
-- re-running this file after a `drop function` + `create function` doesn't quietly re-open them; add
-- any new signed-in-only function to this list.
do $$
declare fn record;
begin
  for fn in
    select p.oid::regprocedure as sig
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public'
      and p.proname in (
        'clear_must_change_password', 'contributor_public_stats', 'contributor_public_stats_by_id',
        'directory', 'leaderboard', 'touch_presence', 'update_own_profile', 'conversation_summaries'
      )
  loop
    execute format('revoke execute on function %s from public, anon', fn.sig);
    execute format('grant execute on function %s to authenticated, service_role', fn.sig);
  end loop;
end $$;
