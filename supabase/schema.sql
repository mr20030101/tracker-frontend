-- One row per conversation: the unread count and the last 5 messages (oldest first), so the inbox
-- list, unread badge, bot reveal timing and notification sound never need a whole thread. Full
-- threads are fetched a page at a time when a chat is opened. Messages the caller deleted for
-- themselves are left out. Runs as the caller, so the messages read policy still applies.
create or replace function public.conversation_summaries()
returns table (other_user_id uuid, unread_count bigint, recent jsonb)
language sql stable set search_path = public
as $$
  with mine as (
    select m.*, case when m.sender_id = auth.uid() then m.recipient_id else m.sender_id end as other_id
    from public.messages m
    where (m.sender_id = auth.uid() and not m.deleted_by_sender)
       or (m.recipient_id = auth.uid() and not m.deleted_by_recipient)
  )
  select o.other_id,
    count(*) filter (where o.recipient_id = auth.uid() and o.read_at is null),
    (select jsonb_agg(to_jsonb(x) - 'other_id' order by x.id)
       from (select * from mine mm where mm.other_id = o.other_id order by mm.id desc limit 5) x)
  from mine o
  group by o.other_id
$$;

grant execute on function public.conversation_summaries() to authenticated;

-- Ranks a contributor's own teammates (same lead_id) by tasks submitted in a date range, which
-- the scoped "profiles read own or manager" policy can't do on its own — same rationale as
-- directory() above, but counting submissions instead of listing presence, and scoped to one
-- team instead of everyone. Two contributors both without a lead (lead_id is null) are still
-- teammates of each other. Matches a submission to its contributor by user_id OR cb_email
-- (case-insensitive), same as the dashboard summary, since a submission logged for someone else
-- by their lead/admin carries that contributor's cb_email but the logger's user_id.
drop function if exists public.leaderboard(date, date);
create function public.leaderboard(range_start date, range_end date)
returns table (user_id uuid, name text, avatar_url text, cb_email text, tasks_submitted bigint)
language sql stable security definer set search_path = public
as $$
  select
    p.id as user_id,
    p.name,
    p.avatar_url,
    p.email as cb_email,
    (
      select count(*) from public.task_submissions s
      where s.status = 'submitted'
        and s.date >= range_start
        and s.date <= range_end
        and (s.user_id = p.id or lower(s.cb_email) = lower(p.email))
    ) as tasks_submitted
  from public.profiles p
  where p.role = 'contributor' and p.is_active
    and p.lead_id is not distinct from (select lead_id from public.profiles where id = auth.uid())
  order by tasks_submitted desc, p.name asc
$$;

grant execute on function public.leaderboard(date, date) to authenticated;

-- Lets any active user open a peer contributor's profile and see their
