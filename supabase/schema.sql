alter table public.resources enable row level security;
alter table public.house_rules enable row level security;

create policy "profiles read own or manager" on public.profiles for select using (id = auth.uid() or public.is_manager());
create policy "users create own profile" on public.profiles for insert with check (id = auth.uid() and role = 'contributor');
create policy "profiles managers update" on public.profiles for update using (public.is_manager()) with check (public.is_manager());

create policy "active users read projects" on public.projects for select using (public.is_active_user());
create policy "managers manage projects" on public.projects for all using (public.is_manager()) with check (public.is_manager());
create policy "active users read resources" on public.resources for select using (public.is_active_user());
create policy "managers manage resources" on public.resources for all using (public.is_manager()) with check (public.is_manager());
create policy "active users read rules" on public.house_rules for select using (public.is_active_user());
create policy "managers manage rules" on public.house_rules for all using (public.is_manager()) with check (public.is_manager());

create policy "users read permitted submissions" on public.task_submissions for select using (public.is_manager() or user_id = auth.uid());
create policy "users create own submissions" on public.task_submissions for insert with check (public.is_manager() or user_id = auth.uid());
create policy "users update permitted submissions" on public.task_submissions for update using (public.is_manager() or user_id = auth.uid()) with check (public.is_manager() or user_id = auth.uid());
create policy "users delete permitted submissions" on public.task_submissions for delete using (public.is_manager() or user_id = auth.uid());

create policy "users read own targets" on public.weekly_targets for select using (public.is_manager() or user_id = auth.uid());
create policy "managers manage targets" on public.weekly_targets for all using (public.is_manager()) with check (public.is_manager());