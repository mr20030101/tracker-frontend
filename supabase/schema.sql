-- Messaging is open to any two active users, independent of lead attachment.
create policy "users read own messages" on public.messages for select
  using (sender_id = auth.uid() or recipient_id = auth.uid());
create policy "active users send messages" on public.messages for insert
  with check (sender_id = auth.uid() and public.is_active_user() and public.is_active_profile(recipient_id));
create policy "recipients mark messages read" on public.messages for update
  using (recipient_id = auth.uid())
  with check (recipient_id = auth.uid());
-- Lets a sender flip their own deleted_by_sender flag; the trigger above
-- still blocks them from touching anything else, including the recipient's flag.
create policy "senders update own messages" on public.messages for update
  using (sender_id = auth.uid())
  with check (sender_id = auth.uid());

