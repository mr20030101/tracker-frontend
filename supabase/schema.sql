create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  email text unique not null,
  role text not null default 'contributor' check (role in ('contributor', 'lead', 'admin')),
  shift text,
  meet_link text,
  is_active boolean not null default true,
  last_seen_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- profiles already exists in production, so create table above is a no-op there;
-- this is what actually adds the column to the live database.
alter table public.profiles add column if not exists last_seen_at timestamptz;

create table if not exists public.activity_logs (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete set null,
  email text,
  event text not null check (event in ('login', 'login_failed', 'logout')),
  user_agent text,
  created_at timestamptz not null default now()
);

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  name text unique not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.task_submissions (
  id bigint generated by default as identity primary key,
  task_id text,
  cb_email text not null,
  user_id uuid references public.profiles(id) on delete set null,
  project_id bigint references public.projects(id) on delete set null,
  stage text not null default 'attempt' check (stage in ('attempt', 'l0', 'l1')),
  status text not null default 'in_progress' check (status in ('submitted', 'in_progress', 'empty', 'expired', 'claimed_by_another')),
  notes text,
  date date,
  submitted_at date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.weekly_targets (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  week_start date not null,
  target integer not null default 50,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, week_start)
);

create table if not exists public.resources (
  id bigint generated by default as identity primary key,
  category text not null,
  title text not null,
  url text not null,
  project_id bigint references public.projects(id) on delete set null,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.house_rules (
  id bigint generated by default as identity primary key,
  project_id bigint references public.projects(id) on delete set null,
  type text not null default 'rule' check (type in ('info', 'rule')),
  title text,
  body text not null,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists task_submissions_user_id_idx on public.task_submissions(user_id);
