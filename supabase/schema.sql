-- Lets any signed-in user rename themselves, set their own avatar, Remotasks worker ID, shift and
-- bio, without granting a general self-update policy on profiles (which would also open
-- role/lead_id/is_active to direct tampering). Only these fields are ever touched, and only for
-- the caller's own row. Dropped first since an earlier-arity version would otherwise stay
-- callable alongside this one as a separate overload.
drop function if exists public.update_own_profile(text, text);
drop function if exists public.update_own_profile(text, text, text);
create or replace function public.update_own_profile(
  new_name text,
  new_avatar_url text,
  new_remotasks_id text default null,
  new_shift text default null,
  new_bio text default null
)
returns public.profiles
language plpgsql security definer set search_path = public
as $$
declare
  updated public.profiles;
begin
  if new_name is null or trim(new_name) = '' then
    raise exception 'Name is required.';
  end if;

  update public.profiles
  set name = trim(new_name),
      avatar_url = new_avatar_url,
      remotasks_id = nullif(trim(coalesce(new_remotasks_id, '')), ''),
      shift = nullif(trim(coalesce(new_shift, '')), ''),
      bio = nullif(trim(coalesce(new_bio, '')), ''),
      updated_at = now()
  where id = auth.uid()
  returning * into updated;

  return updated;
end;
$$;

grant execute on function public.update_own_profile(text, text, text, text, text) to authenticated;

